func init() { register(140, newHooksCmd) }

// Hook shim markers: shims written by mygit carry hookMarker; the shell
// hooks of the Python plugin (setup_repo.py) carry legacyHookMarker and may
// be replaced by install, but uninstall only removes mygit's own.
const (
	hooksDir         = ".githooks"
	hookMarker       = "generated by mygit"
	legacyHookMarker = "Generated by my-git setup_repo.py"
)

func newHooksCmd(a *App) *cobra.Command {
	s := newSession(a)
	cmd := &cobra.Command{
		Use:   "hooks",
		Short: "install, remove or inspect the git hook shims (.githooks → mygit hook)",
	}
	var force bool
	install := &cobra.Command{
		Use:   "install",
		Short: "write .githooks/{commit-msg,pre-commit,pre-push} and set core.hooksPath (dry run first)",
		Args:  cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			p, env, err := s.planner(cmd, args)
			if err != nil {
				return err
			}
			if err := env.RequireRepo(); err != nil {
				return err
			}
			if err := planHooksInstall(a, env, p, force); err != nil {
				return err
			}
			return s.run(cmd, p, nil)
		},
	}
	install.Flags().BoolVar(&force, "force", false, "replace hook files that were not written by mygit")
	s.addOutFlag(install)
	uninstall := &cobra.Command{
		Use:   "uninstall",
		Short: "remove the mygit hook shims and unset core.hooksPath (dry run first)",
		Args:  cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			p, env, err := s.planner(cmd, args)
			if err != nil {
				return err
			}
			if err := env.RequireRepo(); err != nil {
				return err
			}
			if err := planHooksUninstall(a, env, p); err != nil {
				return err
			}
			return s.run(cmd, p, nil)
		},
	}
	s.addOutFlag(uninstall)
	status := &cobra.Command{
		Use:   "status",
		Short: "show which hook shims are installed and whether git uses them",
		Args:  cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			env, err := s.env(cmd)
			if err != nil {
				return err
			}
			if err := env.RequireRepo(); err != nil {
				return err
			}
			st := hooksStatus(a, env)
			if a.Opts.JSON {
				return emitJSON(a.Out, st)
			}
			printHooksStatus(a, st)
			return nil
		},
	}
	cmd.AddCommand(install, uninstall, status)
	return cmd
}

// hookFile describes one shim on disk.
type hookFile struct {
	Name    string      `json:"name"`
	Path    string      `json:"path"`
	State   string      `json:"state"` // missing | current | outdated | legacy | foreign
	Content string      `json:"-"`     // current content ("" when missing)
	Mode    fs.FileMode `json:"-"`
}

// HooksStatus is the --json output of `mygit hooks status`.
type HooksStatus struct {
	HooksPath string     `json:"hooksPath"` // core.hooksPath ("" = unset)
	Active    bool       `json:"active"`    // core.hooksPath points at .githooks
	Hooks     []hookFile `json:"hooks"`
	Installed bool       `json:"installed"` // active and every shim current
}

func hookPath(env *mgapp.Env, name string) string {
	return filepath.Join(env.RepoRoot, hooksDir, name)
}

// readHook inspects one shim and compares it with the rendered template.
func readHook(env *mgapp.Env, name, want string) hookFile {
	h := hookFile{Name: name, Path: hookPath(env, name), State: "missing"}
	b, err := os.ReadFile(h.Path)
	if err != nil {
		return h
	}
	if fi, err := os.Stat(h.Path); err == nil {
		h.Mode = fi.Mode().Perm()
	}
	h.Content = string(b)
	switch {
	case h.Content == want:
		h.State = "current"
	case strings.Contains(h.Content, hookMarker):
		h.State = "outdated"
	case strings.Contains(h.Content, legacyHookMarker):
		h.State = "legacy"
	default:
		h.State = "foreign"
	}
	return h
}

func renderShims() (map[string]string, error) {
	set := tmpl.Default()
	out := map[string]string{}
	for _, n := range tmpl.HookNames() {
		s, err := set.RenderHook(tmpl.HookData{Name: n})
		if err != nil {
			return nil, err
		}
		out[n] = s
	}
	return out, nil
}

func hooksStatus(a *App, env *mgapp.Env) HooksStatus {
	var st HooksStatus
	st.HooksPath, _, _ = env.Git.ConfigGet(a.Context(), "core.hooksPath")
	st.Active = isHooksDir(st.HooksPath)
	shims, err := renderShims()
	if err != nil {
		shims = map[string]string{}
	}
	st.Installed = st.Active
	for _, n := range tmpl.HookNames() {
		h := readHook(env, n, shims[n])
		h.Path = env.Display(h.Path)
		st.Hooks = append(st.Hooks, h)
		st.Installed = st.Installed && h.State == "current"
	}
	return st
}

func isHooksDir(p string) bool {
	p = strings.TrimSuffix(filepath.ToSlash(p), "/")
	return p == hooksDir || p == "./"+hooksDir
}

func printHooksStatus(a *App, st HooksStatus) {
	path := st.HooksPath
	if path == "" {
		path = "(unset: git uses .git/hooks)"
	}
	mark := "✗"
	if st.Active {
		mark = "✓"
	}
	a.Printf("%s core.hooksPath  %s\n", mark, path)
	for _, h := range st.Hooks {
		m := "✗"
		if h.State == "current" {
			m = "✓"
		}
		a.Printf("%s %-14s %-9s %s\n", m, h.Name, h.State, h.Path)
	}
	if !st.Installed {
		a.Printf("install or update: mygit hooks install\n")
	}
}

// planHooksInstall records the steps that make the shims current and
// point core.hooksPath at them. Files not written by mygit (or the Python
// plugin) are only replaced with force.
func planHooksInstall(a *App, env *mgapp.Env, p *mgapp.Planner, force bool) error {
	shims, err := renderShims()
	if err != nil {
		return err
	}
	for _, n := range tmpl.HookNames() {
		h := readHook(env, n, shims[n])
		switch h.State {
		case "foreign":
			if !force {
				return fmt.Errorf("%s exists and was not written by mygit; move it away or pass --force", env.Display(h.Path))
			}
		case "current":
			if a.GOOS == "windows" || h.Mode&0o111 != 0 {
				continue
			}
		}
		if h.State != "current" {
			p.WriteFile(h.Path, shims[n], fmt.Sprintf("write %s (shim → mygit hook %s)", env.Display(h.Path), n))
		}
		if a.GOOS != "windows" && (h.State == "missing" || h.Mode&0o111 == 0) {
			// git runs hooks only when they are executable (Git for Windows ignores the bit)
			p.Cmd(execx.Cmd{Name: "chmod", Args: []string{"0755", h.Path}, Dir: env.RepoRoot}, "make "+env.Display(h.Path)+" executable")
		}
	}
	cur, _, _ := env.Git.ConfigGet(a.Context(), "core.hooksPath")
	if !isHooksDir(cur) {
		if cur != "" {
			p.Note("core.hooksPath was %q; hooks in that directory stop running", cur)
		}
		p.Git(mgapp.GitDescription([]string{"config", "core.hooksPath", hooksDir}, ""), "config", "core.hooksPath", hooksDir)
	}
	return nil
}

// planHooksUninstall removes only shims carrying the mygit marker, and
// unsets core.hooksPath when it points at .githooks and nothing else is
// left there.
func planHooksUninstall(a *App, env *mgapp.Env, p *mgapp.Planner) error {
	removed := map[string]bool{}
	for _, n := range tmpl.HookNames() {
		h := readHook(env, n, "")
		switch {
		case h.State == "missing":
		case strings.Contains(h.Content, hookMarker):
			p.Cmd(removeFileCmd(a.GOOS, h.Path, env.RepoRoot), "remove "+env.Display(h.Path))
			removed[filepath.Base(h.Path)] = true
		default:
			p.Note("kept %s: it was not written by mygit", env.Display(h.Path))
		}
	}
	cur, _, _ := env.Git.ConfigGet(a.Context(), "core.hooksPath")
	if !isHooksDir(cur) {
		return nil
	}
	entries, err := os.ReadDir(filepath.Join(env.RepoRoot, hooksDir))
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	for _, e := range entries {
		if !removed[e.Name()] {
			p.Note("kept core.hooksPath=%s: %s still holds %s", hooksDir, hooksDir, e.Name())
			return nil
		}
	}
	p.Git("git config --unset core.hooksPath", "config", "--unset", "core.hooksPath")
	return nil
}

// removeFileCmd is the plan step that deletes a file.
// TODO(orchestrator): replace with a `mygit file remove` step next to
// `mygit file write` once internal/app has one.
func removeFileCmd(goos, path, dir string) execx.Cmd {
	if goos == "windows" {
		return execx.Cmd{Name: "powershell", Args: []string{"-NoProfile", "-Command", "Remove-Item", "-LiteralPath", path}, Dir: dir}
	}
	return execx.Cmd{Name: "rm", Args: []string{"-f", path}, Dir: dir}
}
