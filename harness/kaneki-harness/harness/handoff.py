"""`sdlc handoff`: the page a fresh controller session starts from (plan D9).

feature-flags ran one Opus controller for 5 h 20 m and 212 API calls; its context grew from 60 K to 333 K and ran out
(a3c4afd6:2751), and controllers were 55% of the ticket's tokens. The lean controller is a fresh session (Sonnet by
default) per phase that reads this file instead of the artifacts: everything here comes from the driver's own data
(state, decision log, questions, budget, environment), so writing it costs no judgement and it cannot drift from the
ticket. The controller regenerates it at every phase boundary and when it stops.
"""

from __future__ import annotations

from typing import Any

MAX_EVENTS = 8


def build(s: Any) -> list[str]:
    from . import board
    from . import questions as Q
    from .state import ready_nodes, settled
    tdir = s.ticket.dir
    order = s.order
    done = [n for n in order if settled(s.state, n)]
    ready = ready_nodes(s.graph, order, s.state)
    wait = board.waiting(s)
    gens = {n: s.state["nodes"][n]["generation"] for n in order if s.state["nodes"].get(n)}
    lines = [f"# Handoff: {s.ctx['ticket']} ({s.ctx['kind']}, lane {s.ctx.get('lane') or 'full'})", "",
             "Generated by `sdlc handoff` from the driver's data; regenerate it, never edit it. Start a fresh controller "
             "session from this page: do not re-read earlier artifacts, ask the driver (`sdlc status --compact`, "
             "`sdlc check`, `sdlc questions`).", "",
             "## Where the ticket is",
             f"- Settled {len(done)}/{len(order)}: {', '.join(done) or 'none'}",
             f"- Ready now (start every one): {', '.join(ready) or 'none'}",
             f"- Waiting on: {wait['on']} ({wait.get('node')}: {wait.get('reason')})",
             f"- Generations above 1: {', '.join(f'{n} g{g}' for n, g in gens.items() if g > 1) or 'none'}"]
    try:
        batch = Q.batch(tdir)
    except Exception:  # noqa: BLE001 — a broken questions file shows up in the gate, not here
        batch = {"open": [], "answered": 0, "late": []}
    lines += ["", "## Questions"]
    if batch["open"]:
        lines += [f"- OPEN {q['id']} ({q['severity']}, {q['class']}): {q['question'][:160]}" for q in batch["open"][:10]]
    lines.append(f"- answered {batch.get('answered', 0)}, adopted {batch.get('adopted', 0)}, late {len(batch.get('late', []))}")
    events, _ = s.ticket.verify_log()
    keep = [e for e in events if e.get("event") in ("gate", "invalidate", "answer", "lane", "budget-override",
                                                    "judge-miss", "park")][-MAX_EVENTS:]
    lines += ["", "## Last decisions"]
    for e in keep:
        what = e.get("verdict") or e.get("reason") or e.get("status") or e.get("lane") or ""
        lines.append(f"- {e.get('at', '')[:16]} {e['event']} {e.get('node') or e.get('id') or ''}: {str(what)[:120]}")
    if not keep:
        lines.append("- none yet")
    b = board.budget_view(s, ready[0] if ready else None, events)
    if b and b.get("level"):
        lines += ["", "## Budget", f"- {b['level']}" + (f": {'; '.join(b.get('reasons') or [])[:300]}" if b.get("reasons") else "")]
    from . import env as E
    if E.config(s.profile):
        st = E.load_state(s)
        lines += ["", "## Evidence environment",
                  f"- {'server pid ' + str(st['pid']) + ' at ' + str(st.get('baseUrl')) if st.get('pid') else 'not up'}"
                  + (f", database {st['db']}" if st.get("db") else "")]
    lines += ["", "## Next",
              f"- `sdlc plan --ticket {s.ctx['ticket']} --node <node>` for each ready node, then packet → unit → record → "
              "check → gate as the skill says.",
              "- At the next phase boundary (plan approved, code review closed, evidence closed) or before stopping: "
              f"`sdlc handoff --ticket {s.ctx['ticket']}`, then continue in a fresh session."]
    return lines


def write(s: Any) -> dict[str, Any]:
    lines = build(s)
    path = s.ticket.dir / "HANDOFF.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return {"ok": True, "path": str(path), "lines": len(lines)}
